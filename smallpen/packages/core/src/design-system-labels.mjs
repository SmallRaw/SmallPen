export function designSystemLabelLocale(locale) {
  const code = String(locale ?? "en").toLowerCase().replace("-", "_");
  if (code === "zh_cn" || code === "zh" || code === "zh_hans") return "zh_cn";
  if (code === "zh_hant" || code === "zh_tw" || code === "zh_hk") return "zh_hant";
  return "en";
}
